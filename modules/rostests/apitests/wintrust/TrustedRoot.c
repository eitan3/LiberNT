START_TEST(TrustedRoot)
{
    GUID Action = WINTRUST_ACTION_GENERIC_VERIFY_V2;
    WINTRUST_CERT_INFO CertInfo = { sizeof(CertInfo) };
    WINTRUST_DATA Data = { sizeof(Data) };
    CRYPT_PROVIDER_DATA *ProvData;
    CRYPT_PROVIDER_SGNR *Signer;
    PCCERT_CONTEXT Ca, Root;
    HCERTSTORE Store;
    FILETIME Now;
    DWORD i;
    LONG Status;

    Store = CertOpenStore(CERT_STORE_PROV_MEMORY, 0, 0, 0, NULL);
    ok(Store != NULL, "CertOpenStore failed %lu\n", GetLastError());
    if (!Store)
        return;
    ok(CertAddEncodedCertificateToStore(Store, X509_ASN_ENCODING, RootR46, sizeof(RootR46), CERT_STORE_ADD_ALWAYS, &Root),
       "adding the root failed %lu\n", GetLastError());
    ok(CertAddEncodedCertificateToStore(Store, X509_ASN_ENCODING, CodeSigningCaR36, sizeof(CodeSigningCaR36),
                                        CERT_STORE_ADD_ALWAYS, &Ca),
       "adding the CA failed %lu\n", GetLastError());
    if (!Root || !Ca)
    {
        CertCloseStore(Store, 0);
        return;
    }

    GetSystemTimeAsFileTime(&Now);
    CertInfo.psCertContext = (CERT_CONTEXT *)Ca;
    CertInfo.chStores = 1;
    CertInfo.pahStores = &Store;
    CertInfo.psftVerifyAsOf = &Now;
    Data.dwUIChoice = WTD_UI_NONE;
    Data.fdwRevocationChecks = WTD_REVOKE_NONE;
    Data.dwUnionChoice = WTD_CHOICE_CERT;
    Data.pCert = &CertInfo;
    Data.dwStateAction = WTD_STATEACTION_VERIFY;
    Status = WinVerifyTrust(INVALID_HANDLE_VALUE, &Action, &Data);
    ok_hex(Status, ERROR_SUCCESS);
    ProvData = WTHelperProvDataFromStateData(Data.hWVTStateData);
    Signer = ProvData ? WTHelperGetProvSignerFromChain(ProvData, 0, FALSE, 0) : NULL;
    ok(Signer != NULL, "no signer\n");
    if (Signer)
    {
        ok_long(Signer->csCertChain, 2);
        for (i = 0; i < Signer->csCertChain; i++)
        {
            CRYPT_PROVIDER_CERT *Cert = WTHelperGetProvCertFromChain(Signer, i);

            ok(Cert != NULL, "no certificate %lu\n", i);
            if (!Cert)
                continue;
            ok(Cert->fTrustedRoot == (i == Signer->csCertChain - 1), "certificate %lu fTrustedRoot %d\n", i,
               Cert->fTrustedRoot);
            ok(Cert->fSelfSigned == (i == Signer->csCertChain - 1), "certificate %lu fSelfSigned %d\n", i,
               Cert->fSelfSigned);
        }
    }
    Data.dwStateAction = WTD_STATEACTION_CLOSE;
    WinVerifyTrust(INVALID_HANDLE_VALUE, &Action, &Data);
    CertFreeCertificateContext(Ca);
    CertFreeCertificateContext(Root);
    CertCloseStore(Store, 0);
}
