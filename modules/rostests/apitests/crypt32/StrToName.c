static
VOID
CheckName(PCWSTR String, DWORD Type, const BYTE *Expected, DWORD ExpectedSize)
{
    BYTE Buffer[512];
    DWORD Size = sizeof(Buffer);
    LPCWSTR Error = (LPCWSTR)1;
    BOOL Ret;

    Ret = CertStrToNameW(X509_ASN_ENCODING, String, Type, NULL, Buffer, &Size, &Error);
    ok(Ret, "%ls (%08lx) failed 0x%08lx at %Id\n", String, Type, GetLastError(),
       Error && Error != (LPCWSTR)1 ? Error - String : (INT_PTR)-1);
    if (!Ret)
        return;
    ok(Error == NULL, "%ls (%08lx) error position %p\n", String, Type, Error);
    ok(Size == ExpectedSize, "%ls (%08lx) size %lu, expected %lu\n", String, Type, Size, ExpectedSize);
    ok(Size == ExpectedSize && !memcmp(Buffer, Expected, Size), "%ls (%08lx) encoding differs\n", String, Type);
}

START_TEST(StrToName)
{
    static const WCHAR Ev[] = L"CN=CPUID, O=CPUID, S=Nord, C=FR, OID.2.5.4.15=Private Organization, "
                              L"OID.1.3.6.1.4.1.311.60.2.1.3=FR, SERIALNUMBER=493 590 202 00047";
    BYTE Buffer[64];
    DWORD Size;
    LPCWSTR Error;

    CheckName(Ev, CERT_X500_NAME_STR, EvSubject, sizeof(EvSubject));
    CheckName(Ev, CERT_X500_NAME_STR | CERT_NAME_STR_REVERSE_FLAG, EvSubjectReversed, sizeof(EvSubjectReversed));
    CheckName(Ev, CERT_OID_NAME_STR, EvSubject, sizeof(EvSubject));
    CheckName(L"OID.2.5.4.15=Private Organization", CERT_X500_NAME_STR, BusinessCategory, sizeof(BusinessCategory));
    CheckName(L"2.5.4.15=Private Organization", CERT_X500_NAME_STR, BusinessCategory, sizeof(BusinessCategory));
    CheckName(L"OID.1.3.6.1.4.1.311.60.2.1.3=FR", CERT_X500_NAME_STR, JurisdictionCountry, sizeof(JurisdictionCountry));
    CheckName(L"oid.2.5.4.15=x", CERT_X500_NAME_STR, LowerCaseOid, sizeof(LowerCaseOid));
    CheckName(L"CN=CPUID, O=CPUID", CERT_X500_NAME_STR, CnThenO, sizeof(CnThenO));
    CheckName(L"CN=CPUID, O=CPUID", CERT_X500_NAME_STR | CERT_NAME_STR_REVERSE_FLAG, OThenCn, sizeof(OThenCn));

    Size = sizeof(Buffer);
    Error = NULL;
    SetLastError(0xdeadbeef);
    ok(!CertStrToNameW(X509_ASN_ENCODING, L"OIDX=1", CERT_X500_NAME_STR, NULL, Buffer, &Size, &Error),
       "an unknown key was accepted\n");
    ok_hex(GetLastError(), CRYPT_E_INVALID_X500_STRING);
}
